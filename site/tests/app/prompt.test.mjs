// Correctness checks for the agent-facing editing prompt.
// Run: node apps/ai-writing-editor/prompt.test.mjs
import { buildEditingPrompt } from "../../src/lib/editor/prompt.js";

let failures = 0;
function check(name, condition) {
  console.log(`${condition ? "✓" : "✗"} ${name}`);
  if (!condition) failures++;
}

const text = `A plain opening.
Studies show this crucial tool will always transform everything.
Honestly, it's not just useful, it's revolutionary.`;
const prompt = buildEditingPrompt(text);

check("includes the original text", prompt.includes(text));
check("includes document statistics", prompt.includes("Document summary:"));
check("includes line-specific findings", /Line 2|Line 3/.test(prompt));
check("includes exact excerpts", /Studies show|Honestly/.test(prompt));
check("includes Clarity findings", prompt.includes("Clarity review:"));
check("includes descriptive signals", prompt.includes("Descriptive signals:"));
check("protects source fidelity", prompt.includes("Do not invent evidence"));
check("ends with the Clarity attribution", prompt.endsWith("Generated by https://clarity.addy.ie"));

const clean = buildEditingPrompt("I made coffee. Then I left for work.");
check("clean text is handled", clean.includes("No line-specific pattern or readability findings."));

console.log(failures ? `\n${failures} FAILED` : "\nAll passed");
process.exit(failures ? 1 : 0);
