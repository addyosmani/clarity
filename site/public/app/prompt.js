import { analyze, CATEGORIES } from "./patterns.js";
import { analyzeClarity } from "./clarity.js";

function lineContext(text, index) {
  const safeIndex = Math.max(0, Math.min(index ?? 0, text.length));
  const start = text.lastIndexOf("\n", safeIndex - 1) + 1;
  const next = text.indexOf("\n", safeIndex);
  const end = next === -1 ? text.length : next;
  const line = text.slice(start, end).trim();
  return {
    number: text.slice(0, start).split("\n").length,
    text: line.length > 220 ? `${line.slice(0, 217)}...` : line,
  };
}

function cleanInline(value) {
  return String(value || "").replace(/\s+/g, " ").trim();
}

function markFindings(text, marks) {
  const findings = [];
  const seen = new Set();
  for (const mark of [...marks].sort((a, b) => a.start - b.start || a.end - b.end)) {
    const meta = CATEGORIES[mark.cat];
    if (!meta) continue;
    const line = lineContext(text, mark.start);
    const excerpt = cleanInline(text.slice(mark.start, mark.end)) || line.text;
    const work = mark.suggestion
      ? `Consider "${mark.suggestion}" if it preserves the meaning.`
      : cleanInline(mark.tip || meta.tip);
    const key = `${line.number}|${mark.cat}|${excerpt}|${work}`;
    if (seen.has(key)) continue;
    seen.add(key);
    findings.push({
      line: line.number,
      category: meta.label,
      excerpt: excerpt.length > 180 ? `${excerpt.slice(0, 177)}...` : excerpt,
      context: line.text,
      work,
    });
  }
  return findings;
}

function clarityFindings(text, checks) {
  return checks
    .filter((check) => check.status === "issue" || check.status === "review")
    .map((check) => ({
      ...check,
      evidence: (check.evidence || []).slice(0, 6).map((excerpt) => {
        const index = text.toLowerCase().indexOf(String(excerpt).toLowerCase());
        return { line: index >= 0 ? lineContext(text, index).number : null, excerpt: cleanInline(excerpt) };
      }),
    }));
}

export function buildEditingPrompt(text) {
  text = text || "";
  const { marks, stats } = analyze(text);
  const clarity = analyzeClarity(text);
  const findings = markFindings(text, marks);
  const clarityItems = clarityFindings(text, clarity.checks);

  const lines = [
    "Edit the text below using the review findings from Clarity Writing Editor.",
    "",
    "Editing requirements:",
    "- Preserve the author's meaning, facts, names, numbers, quotations, links, useful structure, and distinctive voice.",
    "- Do not invent evidence, examples, certainty, or attribution.",
    "- Treat every finding as a review prompt, not a mandatory replacement. Keep wording that is precise, necessary, or intentionally rhythmic.",
    "- Make the smallest useful changes and return only the revised text.",
    "",
    "Document summary:",
    `- ${stats.words} words, ${stats.sentences} sentences, ${stats.paragraphs} paragraphs`,
    `- Surface-pattern score: ${stats.score}/100 (${stats.scoreLabel})`,
    `- Flagged patterns: ${stats.aiTells}`,
    `- Readability grade: ${stats.grade} (${stats.gradeLabel})`,
    "",
    "Line-specific findings:",
  ];

  if (!findings.length) {
    lines.push("- No line-specific pattern or readability findings.");
  } else {
    findings.forEach((finding, index) => {
      lines.push(`${index + 1}. Line ${finding.line} [${finding.category}]`);
      lines.push(`   Excerpt: "${finding.excerpt}"`);
      if (finding.context && finding.context !== finding.excerpt) lines.push(`   Line context: "${finding.context}"`);
      lines.push(`   Work: ${finding.work}`);
    });
  }

  lines.push("", "Clarity review:");
  if (!clarityItems.length) {
    lines.push("- No additional Clarity review prompts.");
  } else {
    for (const check of clarityItems) {
      lines.push(`- ${check.title} [${check.status}]: ${cleanInline(check.detail)}`);
      for (const evidence of check.evidence) {
        lines.push(`  ${evidence.line ? `Line ${evidence.line}` : "Evidence"}: "${evidence.excerpt}"`);
      }
    }
  }

  lines.push("", "Descriptive signals:");
  for (const signal of stats.signals) {
    lines.push(`- ${signal.label}: ${signal.display} [${signal.verdict}]. ${cleanInline(signal.detail)}`);
  }

  lines.push(
    "",
    "Original text:",
    "<text>",
    text,
    "</text>",
    "",
    "Generated by https://clarity.addy.ie",
  );

  return lines.join("\n");
}
